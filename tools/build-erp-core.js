#!/usr/bin/env node
/**
 * Lifts the Priority import out of index.html into the erp Edge Function.
 *
 * Engini's batches have to land exactly the way a Priority Excel file does —
 * same folding of operation rows into פק"ע, same 35 statuses, same "update in
 * place by מספר פק"ע" merge, same rules about whose fields are whose. The only
 * way to promise that is to run the same code, so this script copies it,
 * verbatim, from the app: the same slices tools/plan-test.js already lifts for
 * its tests, plus the DB row converters. Nothing in the copy is edited.
 *
 *   node tools/build-erp-core.js           write supabase/functions/erp/core.mjs
 *   node tools/build-erp-core.js --check   fail if the file is out of date
 *
 * --check runs as part of `npm test` (tools/erp-test.js), so a change to the
 * import in index.html that was not carried over here fails the build instead
 * of quietly making Engini's imports differ from Excel's.
 */
const fs=require("fs"),path=require("path");
const ROOT=path.join(__dirname,"..");
const OUT=path.join(ROOT,"supabase","functions","erp","core.mjs");
const html=fs.readFileSync(path.join(ROOT,"index.html"),"utf8");

const slice=(from,to,what)=>{
  const a=html.indexOf(from),b=html.indexOf(to,a);
  if(a<0||b<0)throw new Error(`could not find ${what} in index.html (${a<0?from:to})`);
  return html.slice(a,b).trimEnd();
};
const line=(starts,what)=>{
  const a=html.indexOf(starts);
  if(a<0)throw new Error(`could not find ${what} in index.html`);
  return html.slice(a,html.indexOf("\n",a));
};

const parts=[
  ["branches",            slice("const BRANCHES=[","function branchList(","the branch catalogue")],
  ["dates",               slice("function isoDay(","// ── DB row converters","isoDay")],
  ["dates",               line("const isoOf=d=>","isoOf")],
  ["DB row converters",   slice("// ── DB row converters","// ── DB load all","the DB row converters")],
  ["statuses",            line("const SL=","SL")],
  ["palette",             line("const COLORS=","COLORS")],
  ["ids and clocks",      [line("const uid=()=>","uid"),line("const todays=","todays"),line("const nowISO=","nowISO")].join("\n")],
  ["progress records",    line("const isQtyLog=","isQtyLog")],
  ["standard times",      slice("const pnKey=","const stdStageMin=","pnKey / pnStdIndex")],
  ["spreadsheet cells",   slice("const xlNorm=s=>","function xlPickSheet(","the spreadsheet cell readers")],
  ["Priority import",     slice("const PRI_H=","function doImport(","the Priority import")],
];

const EXPORTS=["priScan","priBuild","priMergePlan","priAutoMap","priStatus","priRelog","priStamp","progPerStage","progSig",
  "woKey","snKey","xlNorm","xlRow","PRI_H","PRI_S","PRI_NOTE_H","PRI_SKIP","PRI_NEW","PRI_LOG_USER","PRI_LOG_NAME",
  "dbToOrder","orderToDb","dbToLog","logToDb","dbToStage","stageToDb","dbToProject","projectToDb","dbToPnStd","pnStdToDb",
  "branchCode","isQtyLog","nowISO","uid"];

const out=`// ════════════════════════════════════════════════════════════════════════════
// GENERATED by tools/build-erp-core.js from index.html — do not edit by hand.
// ════════════════════════════════════════════════════════════════════════════
// The app's own Priority import, copied verbatim so a batch from Engini lands
// exactly as the same rows would from a Priority Excel file. To change how
// Priority data is read, change index.html and re-run the script.

// What the browser has and the server does not. Every row the function writes
// carries its company explicitly, so rowCid never falls back to this.
const DEFAULT_COMPANY_ID="00000000-0000-0000-0000-000000000001";
let _companyId=null;
const rowCid=x=>(x&&x.companyId)||_companyId;
const deptBranches=d=>sortBranches((d&&d.branches)||[]);

${parts.map(([name,code])=>`// ── from index.html: ${name} ${"─".repeat(Math.max(0,60-name.length))}\n${code}`).join("\n\n")}

export {${EXPORTS.join(",")}};
`;

if(process.argv.includes("--check")){
  const cur=fs.existsSync(OUT)?fs.readFileSync(OUT,"utf8"):"";
  if(cur!==out){console.error("✗ supabase/functions/erp/core.mjs is out of date — run: node tools/build-erp-core.js");process.exit(1)}
  console.log("✓ erp core matches index.html");
}else{
  fs.writeFileSync(OUT,out);
  console.log(`✓ wrote ${path.relative(ROOT,OUT)} (${(out.length/1024).toFixed(0)} KB)`);
}
module.exports={build:()=>out};
